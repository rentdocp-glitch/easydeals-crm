-- LOCAL TEST ONLY. Builds a tiny Supabase-like DB (auth.uid(), roles, RLS) to test the proposed scripts.
do $$ begin create role anon nologin; exception when duplicate_object then null; end $$;
do $$ begin create role authenticated nologin; exception when duplicate_object then null; end $$;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$
  -- same body as Supabase's real auth.uid()
  select coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
                  (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'))::uuid $$;
grant usage on schema auth, public to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
create table public.profiles(id uuid primary key, name text, role text default 'telecaller');
create table public.leads(id bigint generated by default as identity primary key, name text, status text default 'new', remarks text, assigned_to uuid);
create table public.calls(id bigserial primary key, lead_id bigint references public.leads(id) on delete cascade, note text);
create table public.device_calls(id bigserial primary key, lead_id bigint references public.leads(id) on delete cascade, dur int);
create table public.lead_assignment_log(id bigserial primary key, lead_id bigint references public.leads(id) on delete cascade, to_id uuid);
create table public.lead_shares(id bigserial primary key, lead_id bigint references public.leads(id) on delete cascade, user_id uuid);
create function public.ed_is_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') $$;
grant all on all tables in schema public to anon, authenticated;   -- Supabase default grants
grant all on all sequences in schema public to anon, authenticated;
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
alter table public.profiles enable row level security;
-- deliberately weak policy (the risk we are fixing): anyone may update own profile row
create policy p_sel on public.profiles for select to authenticated using (true);
create policy p_upd_own on public.profiles for update to authenticated using (id = auth.uid() or public.ed_is_admin());
create policy p_ins_own on public.profiles for insert to authenticated with check (id = auth.uid() or public.ed_is_admin());
alter table public.leads enable row level security;
create policy l_all on public.leads for all to authenticated using (public.ed_is_admin() or assigned_to = auth.uid()) with check (public.ed_is_admin() or assigned_to = auth.uid());
