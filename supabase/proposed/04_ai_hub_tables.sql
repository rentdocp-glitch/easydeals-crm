-- Safe to run twice. ROLLBACK block at the end.

create table if not exists public.ai_hub_drafts (
  id          bigint generated by default as identity primary key,
  fp          text not null unique,               -- dedupe key, e.g. buyer:123:intro:<updated_at>
  agent       text not null,                      -- Owner Service AI / Buyer RM AI / ...
  entity_kind text not null check (entity_kind in ('buyer','owner','property','report')),
  entity_id   text not null,
  title       text,
  body        text not null,
  status      text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at  timestamptz not null default now(),
  decided_at  timestamptz,
  decided_by  uuid
);
create table if not exists public.ai_hub_activity (
  id   bigint generated by default as identity primary key,
  at   timestamptz not null default now(),
  kind text not null default 'info',
  msg  text not null,
  by_id uuid default auth.uid()
);
alter table public.ai_hub_drafts   enable row level security;
alter table public.ai_hub_activity enable row level security;
drop policy if exists admin_all on public.ai_hub_drafts;
create policy admin_all on public.ai_hub_drafts   for all to authenticated using (ed_is_admin()) with check (ed_is_admin());
drop policy if exists admin_all on public.ai_hub_activity;
create policy admin_all on public.ai_hub_activity for all to authenticated using (ed_is_admin()) with check (ed_is_admin());
revoke all on public.ai_hub_drafts, public.ai_hub_activity from anon;
-- Note: there is deliberately NO column or trigger that sends anything. "approved" only means a human may send it manually.

