-- Har phone ka apna secret key (app login ke baad khud banata hai)
create table if not exists public.device_keys (
  key        text primary key,
  user_id    uuid not null,
  created_at timestamptz default now(),
  last_used  timestamptz
);
alter table public.device_keys enable row level security;   -- koi seedha nahi padh sakta

-- Har aane wale call ka record (missed paying-owner calls dikhane ke liye)
create table if not exists public.call_events (
  id       bigint generated by default as identity primary key,
  at       timestamptz default now(),
  user_id  uuid,
  phone    text,
  bucket   text,      -- paid_owner / buyer / owner_lead / unknown
  title    text,
  detail   text,
  missed   boolean default false,
  called_back boolean default false
);
create index if not exists call_events_at_idx on public.call_events(at desc);
alter table public.call_events enable row level security;
drop policy if exists admin_all on public.call_events;
create policy admin_all on public.call_events for all to authenticated
  using (public.ed_is_admin()) with check (public.ed_is_admin());

-- 1) Logged-in app apne phone ke liye key banata hai
create or replace function public.register_device()
returns text language plpgsql security definer set search_path = public as $$
declare k text;
begin
  if auth.uid() is null or not exists (select 1 from profiles where id = auth.uid()) then
    raise exception 'not allowed';
  end if;
  k := replace(gen_random_uuid()::text,'-','') || replace(gen_random_uuid()::text,'-','');
  insert into device_keys(key, user_id) values (k, auth.uid());
  return k;
end $$;
revoke all on function public.register_device() from public, anon;
grant execute on function public.register_device() to authenticated;

-- helper: kisi bhi text se aakhri 10 digit
create or replace function public.ed_p10(t text) returns text language sql immutable as $$
  select right(regexp_replace(coalesce(t,''),'\D','','g'),10)
$$;

-- 2) Call aaya: number kis bucket ka hai?
create or replace function public.caller_id(n text, k text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  uid uuid; p text; r jsonb := '[]'::jsonb; x record; best text; ttl text; det text;
begin
  select user_id into uid from device_keys where key = k;
  if uid is null then raise exception 'bad device'; end if;
  update device_keys set last_used = now() where key = k;
  p := ed_p10(n);
  if length(p) < 10 then return jsonb_build_object('bucket','unknown','items','[]'::jsonb); end if;

  -- A) Deal Closed Owner: properties table (owner ke ek se zyada number ho sakte hain)
  for x in
    select pr.*, (select count(*) from buyer_leads b where b.property_id = pr.id) as nleads,
           (select count(*) from buyer_leads b where b.property_id = pr.id and b.status in ('Site Visit Scheduled','Site Visit Done')) as nvisits
    from properties pr
    where exists (select 1 from regexp_split_to_table(coalesce(pr.owner_phone,''), '[/,;]') s where ed_p10(s) = p)
  loop
    r := r || jsonb_build_object('bucket','paid_owner',
      'title','⭐ Deal Closed Owner · ' || coalesce(x.owner_name,'Owner'),
      'detail', x.id || ' ' || coalesce(x.project,'') || coalesce(', ' || x.locality,'') || ' · ' || coalesce(x.bhk,'') ||
                coalesce(' · ₹' || round(x.price/100000.0,1) || ' L','') ||
                E'\n' || x.nleads || ' buyer leads · ' || x.nvisits || ' site visits' ||
                case when x.status ilike 'sold%' then ' · SOLD' else '' end);
  end loop;
  -- Deal Closed Owner jo team CRM mein Deal Closed hai par property abhi bani nahi
  for x in select l.* from leads l where l.status = 'deal_closed' and ed_p10(l.phone) = p
           and not exists (select 1 from properties pr where pr.owner_lead_id = l.id::text) loop
    r := r || jsonb_build_object('bucket','paid_owner',
      'title','⭐ Deal Closed Owner · ' || coalesce(x.name,'Owner'),
      'detail', coalesce(x.property,'') || coalesce(', ' || x.locality,'') || coalesce(' · ' || x.bhk,'') || E'\nDeal closed (property card abhi nahi bana)');
  end loop;

  -- B) Buyer: kis property ke liye enquiry
  for x in
    select b.*, pr.project, pr.owner_name, pr.locality, pr.bhk as pbhk, pr.price
    from buyer_leads b left join properties pr on pr.id = b.property_id
    where ed_p10(b.buyer_phone) = p
    order by b.lead_date desc nulls last limit 5
  loop
    r := r || jsonb_build_object('bucket','buyer',
      'title','🧑 Buyer · ' || coalesce(nullif(x.buyer_name,''),'Buyer'),
      'detail', 'Enquiry: ' || coalesce(x.property_id || ' ' || x.project,'property abhi judi nahi') ||
                coalesce(' (owner ' || x.owner_name || ')','') ||
                E'\n' || coalesce(x.source,'') || coalesce(' · ' || to_char(x.lead_date,'DD Mon'),'') || ' · ' || coalesce(x.status,'New'));
  end loop;

  -- C) Owner data (telecaller wala, deal baaki)
  for x in
    select l.*, tc.name as tcn, fe.name as fen
    from leads l left join profiles tc on tc.id = l.tc_id left join profiles fe on fe.id = l.fe_id
    where ed_p10(l.phone) = p and l.status <> 'deal_closed'
    order by l.id desc limit 3
  loop
    r := r || jsonb_build_object('bucket','owner_lead',
      'title','🏠 Owner data · ' || coalesce(nullif(x.name,''),'Owner'),
      'detail', coalesce(nullif(concat_ws(', ', nullif(x.property,''), nullif(x.locality,''), nullif(x.bhk,'')),''),'Property detail nahi') ||
                ' · ' || coalesce(initcap(replace(x.status,'_',' ')),'New') ||
                E'\n' || coalesce('Telecaller: ' || x.tcn,'Telecaller: -') || coalesce(' · FE: ' || x.fen,'') ||
                coalesce(' · Meeting ' || to_char(x.meeting_date,'DD Mon'),'') ||
                coalesce(' · Follow-up ' || to_char(x.follow_date,'DD Mon'),''));
  end loop;

  best := coalesce(r->0->>'bucket','unknown');
  ttl := coalesce(r->0->>'title','📞 Naya number');
  det := coalesce(r->0->>'detail','CRM mein nahi hai · call ke baad lead add karo');
  insert into call_events(user_id, phone, bucket, title, detail) values (uid, p, best, ttl, det);
  return jsonb_build_object('bucket', best, 'items', r);
end $$;
revoke all on function public.caller_id(text,text) from public;
grant execute on function public.caller_id(text,text) to anon, authenticated;

-- 3) Call utha nahi (missed) -> record
create or replace function public.call_missed(n text, k text)
returns void language plpgsql security definer set search_path = public as $$
declare uid uuid;
begin
  select user_id into uid from device_keys where key = k;
  if uid is null then return; end if;
  update call_events set missed = true
  where id = (select id from call_events where user_id = uid and phone = ed_p10(n) and at > now() - interval '10 minutes' order by at desc limit 1);
end $$;
revoke all on function public.call_missed(text,text) from public;
grant execute on function public.call_missed(text,text) to anon, authenticated;

