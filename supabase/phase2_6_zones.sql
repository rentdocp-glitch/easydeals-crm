-- 3) SPELLING NORMALISER: "Hinjawadi Phase 1" = "hinjavadi", "Vadgaon Bk" = "wadgaon budruk" etc.
create or replace function public.ed_norm(t text) returns text language sql immutable as $$
  select coalesce(nullif(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
         regexp_replace(lower(coalesce(t,'')), '\m(phase|ph)\s*[-.]?\s*\d+\M', '', 'g'),   -- phase 1/2/3
         '\mbudruk\M|\mbk\M', 'bk', 'g'),
         '\mkhurd\M|\mkh\M', 'kh', 'g'),
         '[^a-z0-9]', '', 'g'),                                                           -- spaces/punctuation
         'w', 'v', 'g'),                                                                  -- wadgaon = vadgaon
         '(ee|ii)', 'i', 'g'),
         '(aa)', 'a', 'g'),
         '(oo|uu)', 'u', 'g'), ''), regexp_replace(lower(coalesce(t,'')), '\s+', '', 'g'))   -- Devanagari etc. as-is
$$;

-- kisi bhi locality text ke liye pakka (exact) match: poora text, phir pehla hissa ( "(" , "/" , "," se pehle )
create or replace function public.ed_area_exact(t text) returns bigint language sql stable security definer
set search_path = public as $$
  with c as (
    select ed_norm(t) n, 1 o union all
    select ed_norm(split_part(split_part(split_part(coalesce(t,''),'(',1),'/',1),',',1)), 2
  )
  select a.id from c join areas a on a.status = 'approved'
     and (a.norm = c.n or c.n = any (select ed_norm(x) from unnest(a.aliases) x))
  where c.n <> ''
  order by c.o limit 1
$$;

-- 4) AUTO-LINK: koi bhi lead/property save ho, locality pakki mile to zone+area jud jaata hai.
--    Na mile to khaali (Unclassified) - kabhi andaza nahi.
create or replace function public.ed_link_area() returns trigger language plpgsql security definer
set search_path = public as $$
declare aid bigint;
begin
  if tg_op = 'UPDATE' and new.area_id is not distinct from old.area_id
     and new.locality is not distinct from old.locality then
    return new;
  end if;
  if new.area_id is null or (tg_op = 'UPDATE' and new.locality is distinct from old.locality and new.area_id is not distinct from old.area_id) then
    aid := ed_area_exact(new.locality);
    new.area_id := aid;
  end if;
  -- merged area -> uska final area
  if new.area_id is not null then
    select coalesce(a2.id, a.id) into aid from areas a left join areas a2 on a2.id = a.merged_into where a.id = new.area_id;
    new.area_id := aid;
    select zone_id into new.zone_id from areas where id = new.area_id;
  else
    new.zone_id := null;
  end if;
  return new;
end $$;
drop trigger if exists leads_link_area on public.leads;
create trigger leads_link_area before insert or update on public.leads for each row execute function public.ed_link_area();
drop trigger if exists properties_link_area on public.properties;
create trigger properties_link_area before insert or update on public.properties for each row execute function public.ed_link_area();

-- 5) FUNCTIONS FOR THE APP
-- (a) "Kya aapka matlab ... hai?" - milte-julte approved areas
create or replace function public.area_suggest(t text) returns table(id bigint, name text, zone_id int, score real)
language sql stable security definer set search_path = public, extensions as $$
  select a.id, a.name, a.zone_id,
         greatest(similarity(a.norm, ed_norm(t)),
                  coalesce((select max(similarity(ed_norm(x), ed_norm(t))) from unnest(a.aliases) x), 0))::real s
  from areas a
  where a.status = 'approved' and ed_is_staff() and length(ed_norm(t)) >= 3
  order by s desc limit 3
$$;

-- (b) Employee ne "Other" mein naya naam likha -> pending (ya pehle se ho to wahi id)
create or replace function public.area_request(t text, z int) returns jsonb language plpgsql security definer
set search_path = public as $$
declare n text := ed_norm(t); r areas%rowtype; nm text := initcap(trim(regexp_replace(coalesce(t,''),'\s+',' ','g')));
begin
  if not ed_is_staff() then raise exception 'not allowed'; end if;
  if length(n) < 3 then raise exception 'area name too short'; end if;
  select * into r from areas where status in ('approved','pending') and (norm = n or n = any (select ed_norm(x) from unnest(aliases) x)) limit 1;
  if found then return jsonb_build_object('id', r.id, 'name', r.name, 'status', r.status, 'zone_id', r.zone_id); end if;
  insert into areas(name, norm, status, suggested_zone, requested_by, note)
  values (nm, n, 'pending', z, auth.uid(), 'Team ne Other mein joda') returning * into r;
  insert into area_audit(action, area_id, detail) values ('request', r.id, jsonb_build_object('name', nm, 'zone', z));
  return jsonb_build_object('id', r.id, 'name', r.name, 'status', 'pending', 'zone_id', null);
end $$;

-- (c) ADMIN: approve / reject / rezone / rename / merge / alias / deactivate
create or replace function public.area_admin(act text, aid bigint, z int default null, target bigint default null, txt text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare a areas%rowtype; t areas%rowtype; nl int := 0; np int := 0; k int;
begin
  if not ed_is_admin() then raise exception 'only admin'; end if;
  select * into a from areas where id = aid;
  if not found and act <> 'create' then raise exception 'area not found'; end if;

  if act = 'create' then                                   -- naya approved area
    if z is null then raise exception 'zone required'; end if;
    insert into areas(name, norm, zone_id, status, decided_by, decided_at, note)
    values (initcap(trim(txt)), ed_norm(txt), z, 'approved', auth.uid(), now(), 'Admin ne joda') returning * into a;
    act := 'create';
  elsif act = 'approve' then
    if coalesce(z, a.suggested_zone) is null then raise exception 'zone required'; end if;
    update areas set status = 'approved', zone_id = coalesce(z, a.suggested_zone), decided_by = auth.uid(), decided_at = now() where id = aid returning * into a;
  elsif act = 'reject' then
    update areas set status = 'rejected', decided_by = auth.uid(), decided_at = now() where id = aid returning * into a;
  elsif act = 'rezone' then
    update areas set zone_id = z where id = aid returning * into a;
    update leads set zone_id = z where area_id = aid; get diagnostics nl = row_count;
    update properties set zone_id = z where area_id = aid; get diagnostics np = row_count;
  elsif act = 'rename' then
    update areas set aliases = array(select distinct x from unnest(aliases || a.name) x), name = initcap(trim(txt)), norm = ed_norm(txt) where id = aid returning * into a;
  elsif act = 'alias' then
    update areas set aliases = array(select distinct x from unnest(aliases || trim(txt)) x) where id = aid returning * into a;
  elsif act = 'deactivate' then
    update areas set status = 'rejected', note = coalesce(note,'') || ' (band kiya)' where id = aid returning * into a;
  elsif act = 'merge' then                                 -- a ko target mein milao
    select * into t from areas where id = target and status = 'approved';
    if not found then raise exception 'target must be an approved area'; end if;
    update areas set aliases = array(select distinct x from unnest(t.aliases || a.name || a.aliases) x) where id = target;
    update areas set status = 'merged', merged_into = target, decided_by = auth.uid(), decided_at = now() where id = aid;
    update leads set area_id = target where area_id = aid; get diagnostics nl = row_count;
    update properties set area_id = target where area_id = aid; get diagnostics np = row_count;
    select * into a from areas where id = target;
  else
    raise exception 'unknown action';
  end if;

  -- approved area ke naam/spelling se mile purane unclassified records jod do (sirf pakka match)
  if a.status = 'approved' and act in ('create','approve','rename','alias','merge') then
    update leads set area_id = a.id where area_id is null and ed_area_exact(locality) = a.id;
    get diagnostics k = row_count; nl := nl + k;
    update properties set area_id = a.id where area_id is null and ed_area_exact(locality) = a.id;
    get diagnostics k = row_count; np := np + k;
  end if;
  insert into area_audit(action, area_id, detail)
  values (act, coalesce(aid, a.id), jsonb_build_object('name', a.name, 'zone', a.zone_id, 'target', target, 'text', txt, 'leads', nl, 'properties', np));
  return jsonb_build_object('id', a.id, 'name', a.name, 'status', a.status, 'zone_id', a.zone_id, 'leads', nl, 'properties', np);
end $$;

-- (d) ADMIN: ek unclassified locality text ko kisi area se jodo (aur spelling-list mein yaad rakho)
create or replace function public.area_assign_text(loc text, aid bigint) returns jsonb language plpgsql security definer
set search_path = public as $$
declare nl int; np int;
begin
  if not ed_is_admin() then raise exception 'only admin'; end if;
  if not exists (select 1 from areas where id = aid and status = 'approved') then raise exception 'approved area required'; end if;
  if ed_norm(loc) <> '' then
    update areas set aliases = array(select distinct x from unnest(aliases || trim(loc)) x) where id = aid and norm <> ed_norm(loc);
  end if;
  update leads set area_id = aid where area_id is null and coalesce(trim(locality),'') = coalesce(trim(loc),''); get diagnostics nl = row_count;
  update properties set area_id = aid where area_id is null and coalesce(trim(locality),'') = coalesce(trim(loc),''); get diagnostics np = row_count;
  insert into area_audit(action, area_id, detail) values ('assign', aid, jsonb_build_object('text', loc, 'leads', nl, 'properties', np));
  return jsonb_build_object('leads', nl, 'properties', np);
end $$;

-- (e) ADMIN: unclassified localities ki list (gintī ke saath)
create or replace function public.area_unclassified() returns table(src text, locality text, n bigint)
language sql stable security definer set search_path = public as $$
  select 'leads', coalesce(nullif(trim(locality),''),'(khaali)'), count(*) from leads where area_id is null and ed_is_admin() group by 2
  union all
  select 'properties', coalesce(nullif(trim(locality),''),'(khaali)'), count(*) from properties where area_id is null and ed_is_admin() group by 2
  order by 3 desc
$$;

-- (f) ADMIN: zone jodo / naam badlo / band karo; team switch
create or replace function public.zone_admin(act text, zid int, txt text default null) returns void language plpgsql security definer
set search_path = public as $$
begin
  if not ed_is_admin() then raise exception 'only admin'; end if;
  if act = 'create' then insert into zones(name, sort) values (trim(txt), (select coalesce(max(sort),0)+1 from zones));
  elsif act = 'rename' then update zones set name = trim(txt) where id = zid;
  elsif act = 'toggle' then update zones set active = not active where id = zid;
  elsif act = 'team_ui' then update app_settings set v = to_jsonb(txt = 'on') where k = 'zone_ui_team';
  else raise exception 'unknown action'; end if;
  insert into area_audit(action, detail) values ('zone_' || act, jsonb_build_object('zone', zid, 'text', txt));
end $$;

revoke all on function public.area_suggest(text), public.area_request(text,int), public.area_admin(text,bigint,int,bigint,text),
  public.area_assign_text(text,bigint), public.area_unclassified(), public.zone_admin(text,int,text) from public, anon;
grant execute on function public.area_suggest(text), public.area_request(text,int), public.area_admin(text,bigint,int,bigint,text),
  public.area_assign_text(text,bigint), public.area_unclassified(), public.zone_admin(text,int,text) to authenticated;

