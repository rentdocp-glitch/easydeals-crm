-- =====================================================================
-- EasyDeals CRM - Phase 2 (Buyers) - STEP 1: nayi tables
-- Purani tables (leads, calls, device_calls, profiles) ko yeh file
-- bilkul nahi chhedti. Sirf 3 nayi tables banti hain, aur unhe sirf
-- ADMIN role dekh/badal sakta hai. Do baar chalane par bhi safe hai.
-- =====================================================================

-- Admin check (profiles.role = 'admin')
create or replace function public.ed_is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- 1) PROPERTIES (har deal-closed owner ki property, ED-001...)
create table if not exists public.properties (
  id            text primary key,                 -- ED-001
  owner_lead_id text,                             -- purani leads table ki owner lead (agar judi ho)
  owner_name    text,
  owner_phone   text,
  project       text,                             -- Property / project name
  ptype         text default 'Flat',
  bhk           text,
  address       text,
  locality      text,
  city          text default 'Pune',
  sqft          numeric,
  price         numeric,                          -- rupees
  status        text default 'Available',         -- Available / Sold / Rented / On Hold
  date_added    date default current_date,
  remarks       text,
  id_99acres    text,
  id_magicbricks text,
  id_housing    text,
  portal_status text,
  tour_url      text,
  video_url     text,
  photos_url    text,
  reel_url      text,
  created_at    timestamptz default now(),
  updated_at    timestamptz default now()
);

-- 2) BUYER LEADS (ek buyer + ek property = ek row)
create table if not exists public.buyer_leads (
  id            bigint generated by default as identity primary key,
  code          text unique,                      -- L-0001
  lead_date     date default current_date,
  property_id   text references public.properties(id) on update cascade on delete set null, -- khali = Unassigned
  source        text default 'Other',             -- 99acres / Magicbricks / Housing.com / Website / Other
  listing_id    text,
  buyer_name    text,
  buyer_phone   text,
  requirement   text,
  status        text default 'New',               -- New / Contacted / Follow-up / Site Visit Scheduled / Site Visit Done / Not Interested / Deal Closed
  last_fu       date,
  next_fu       date,
  visit_at      timestamptz,
  remarks       text,
  assigned_to   uuid,                             -- baad mein: jo buyers se baat karega
  created_at    timestamptz default now(),
  updated_at    timestamptz default now()
);
create index if not exists buyer_leads_prop_idx  on public.buyer_leads(property_id);
create index if not exists buyer_leads_phone_idx on public.buyer_leads(buyer_phone);
create index if not exists buyer_leads_nextfu_idx on public.buyer_leads(next_fu);

-- 3) BUYER HISTORY (har call / status change / note ka record)
create table if not exists public.buyer_history (
  id         bigint generated by default as identity primary key,
  buyer_id   bigint references public.buyer_leads(id) on delete cascade,
  at         timestamptz default now(),
  by_id      uuid default auth.uid(),
  status     text,
  note       text
);
create index if not exists buyer_history_buyer_idx on public.buyer_history(buyer_id);

-- updated_at auto
create or replace function public.ed_touch() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists properties_touch on public.properties;
create trigger properties_touch before update on public.properties for each row execute function public.ed_touch();
drop trigger if exists buyer_leads_touch on public.buyer_leads;
create trigger buyer_leads_touch before update on public.buyer_leads for each row execute function public.ed_touch();

-- SIRF ADMIN: Row Level Security
alter table public.properties    enable row level security;
alter table public.buyer_leads   enable row level security;
alter table public.buyer_history enable row level security;

drop policy if exists admin_all on public.properties;
create policy admin_all on public.properties    for all to authenticated using (public.ed_is_admin()) with check (public.ed_is_admin());
drop policy if exists admin_all on public.buyer_leads;
create policy admin_all on public.buyer_leads   for all to authenticated using (public.ed_is_admin()) with check (public.ed_is_admin());
drop policy if exists admin_all on public.buyer_history;
create policy admin_all on public.buyer_history for all to authenticated using (public.ed_is_admin()) with check (public.ed_is_admin());

